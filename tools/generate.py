def c_string(text: str) -> str:
    """A C narrow string literal holding text's UTF-8 bytes, escaped so it is pure ASCII."""
    out = []
    for byte in text.encode("utf-8"):
        ch = chr(byte)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\n":
            out.append("\\n")
        elif 0x20 <= byte < 0x7F:
            out.append(ch)
        else:
            # Octal, not \x: a hex escape would swallow a following hex digit.
            out.append("\\%03o" % byte)
    return '"' + "".join(out) + '"'


def c_wide_string(text: str) -> str:
    """An L"..." literal holding text as UTF-16 code units (Windows wchar_t)."""
    out = []
    raw = text.encode("utf-16-le")
    for i in range(0, len(raw), 2):
        unit = raw[i] | (raw[i + 1] << 8)
        ch = chr(unit) if unit < 0x80 else None
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch is not None and 0x20 <= unit < 0x7F:
            out.append(ch)
        else:
            out.append("\\x%04x\" L\"" % unit)  # split so the next char can't extend the escape
    return 'L"' + "".join(out) + '"'


def _rust_escape(text: str) -> str:
    out = []
    for ch in text:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\n":
            out.append("\\n")
        elif 0x20 <= code < 0x7F:
            out.append(ch)
        else:
            out.append("\\u{%x}" % code)
    return '"' + "".join(out) + '"'


def byte_rows(data: bytes, indent: str) -> str:
    rows = []
    for i in range(0, len(data), 12):
        rows.append(indent + ", ".join("0x%02x" % b for b in data[i:i + 12]) + ",")
    return "\n".join(rows)


def route_by_id(contract: dict) -> dict:
    return {route["id"]: route for route in contract["routes"]}


# ---------------------------------------------------------------------------
# generated/blorg_contract.h  (kernel-safe: macros only)
# ---------------------------------------------------------------------------

def render_c_header(contract: dict) -> str:
    v = contract["version"]
    lines = [
        "//",
        "// " + BANNER,
        "//",
        "// The server-rs <-> BlorgFS wire contract. Macros only, so it is safe to",
        "// include from kernel code. Route strings are literals so they can be",
        "// concatenated into a request format string at compile time.",
        "//",
        "",
        "#pragma once",
        "",
        "#define BLORG_CONTRACT_VERSION_MAJOR %d" % v["major"],
        "#define BLORG_CONTRACT_VERSION_MINOR %d" % v["minor"],
        "",
        "#define BLORG_CONTRACT_QUERY_PATH %s" % c_string(contract["transport"]["query_path_key"]),
        "#define BLORG_CONTRACT_MAX_BODY_BYTES %d" % contract["transport"]["max_body_bytes"],
        "#define BLORG_CONTRACT_MAX_HEADER_BYTES %d" % contract["transport"]["max_header_bytes"],
        "",
    ]
    for route in contract["routes"]:
        lines.append("#define BLORG_CONTRACT_ROUTE_%s %s" % (route["id"], c_string(route["path"])))
        lines.append("#define BLORG_CONTRACT_STATUS_%s_OK %d" % (route["id"], route["success_status"]))
    lines.append("")
    for error in contract["error_statuses"]:
        lines.append("#define BLORG_CONTRACT_STATUS_%s %d" % (error["id"], error["status"]))
    lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# generated/blorg_contract_fixtures.h  (tests only)
# ---------------------------------------------------------------------------

def render_c_fixtures(contract: dict, encoded: dict[str, bytes]) -> str:
    out = [
        "//",
        "// " + BANNER,
        "//",
        "// Golden fixtures for the driver's sandbox tests: the exact request bytes",
        "// the driver must send, and FlatBuffer bodies (encoded by flatc, the same",
        "// encoder family server-rs uses) with the values they must decode to.",
        "// Usermode tests only -- not for kernel code.",
        "//",
        "",
        "#pragma once",
        "",
        '#include "blorg_contract.h"',
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "#include <wchar.h>",
        "",
        "typedef struct BLORG_CONTRACT_REQUEST",
        "{",
        "    const char* Id;",
        "    const wchar_t* Path;      // as the driver receives it from Windows",
        "    int HasRange;",
        "    uint64_t RangeFirst;      // inclusive",
        "    uint64_t RangeLast;       // inclusive",
        "    const char* Wire;         // exact bytes the driver must send",
        "} BLORG_CONTRACT_REQUEST;",
        "",
        "typedef struct BLORG_CONTRACT_FILE",
        "{",
        "    const wchar_t* Name;",
        "    uint64_t Size, Created, Modified, Accessed;",
        "} BLORG_CONTRACT_FILE;",
        "",
        "typedef struct BLORG_CONTRACT_SUBDIR",
        "{",
        "    const wchar_t* Name;",
        "    uint64_t Created, Modified, Accessed;",
        "} BLORG_CONTRACT_SUBDIR;",
        "",
        "typedef struct BLORG_CONTRACT_LISTING",
        "{",
        "    const char* Id;",
        "    const unsigned char* Bytes;",
        "    size_t ByteCount;",
        "    const BLORG_CONTRACT_FILE* Files;",
        "    size_t FileCount;",
        "    const BLORG_CONTRACT_SUBDIR* SubDirs;",
        "    size_t SubDirCount;",
        "} BLORG_CONTRACT_LISTING;",
        "",
        "typedef struct BLORG_CONTRACT_ENTRY",
        "{",
        "    const char* Id;",
        "    const unsigned char* Bytes;",
        "    size_t ByteCount;",
        "    uint64_t Size, Created, Modified, Accessed;",
        "    int Directory;",
        "} BLORG_CONTRACT_ENTRY;",
        "",
    ]

    out.append("static const BLORG_CONTRACT_REQUEST BlorgContractRequests[] =")
    out.append("{")
    for req in contract["requests"]:
        first, last = req.get("range", [0, 0])
        out.append("    { %s, %s, %d, %dULL, %dULL, %s }," % (
            c_string(req["id"]), c_wide_string(req["path"]), 1 if "range" in req else 0,
            first, last, c_string(req["wire"])))
    out.append("};")
    out.append("")

    listings, entries = [], []
    for fixture in contract["fixtures"]:
        fid = fixture["id"]
        data = encoded[fid]
        out.append("static const unsigned char BlorgContractFixture_%s[] =" % fid)
        out.append("{")
        out.append(byte_rows(data, "    "))
        out.append("};")
        out.append("")
        if fixture["root_type"].endswith(".Directory"):
            files = fixture["data"]["files"]
            subdirs = fixture["data"]["subdirectories"]
            # A zero-length array is not valid C, so empty lists get a null pointer.
            if files:
                out.append("static const BLORG_CONTRACT_FILE BlorgContractFixture_%s_Files[] =" % fid)
                out.append("{")
                for f in files:
                    out.append("    { %s, %dULL, %dULL, %dULL, %dULL }," % (
                        c_wide_string(f["name"]), f["size"], f["created"], f["modified"], f["accessed"]))
                out.append("};")
                out.append("")
            if subdirs:
                out.append("static const BLORG_CONTRACT_SUBDIR BlorgContractFixture_%s_SubDirs[] =" % fid)
                out.append("{")
                for d in subdirs:
                    out.append("    { %s, %dULL, %dULL, %dULL }," % (
                        c_wide_string(d["name"]), d["created"], d["modified"], d["accessed"]))
                out.append("};")
                out.append("")
            listings.append("    { %s, BlorgContractFixture_%s, sizeof(BlorgContractFixture_%s), %s, %d, %s, %d }," % (
                c_string(fid), fid, fid,
                ("BlorgContractFixture_%s_Files" % fid) if files else "NULL", len(files),
                ("BlorgContractFixture_%s_SubDirs" % fid) if subdirs else "NULL", len(subdirs)))
        else:
            d = fixture["data"]
            entries.append("    { %s, BlorgContractFixture_%s, sizeof(BlorgContractFixture_%s), %dULL, %dULL, %dULL, %dULL, %d }," % (
                c_string(fid), fid, fid, d["size"], d["created"], d["modified"], d["accessed"], 1 if d["directory"] else 0))

    out.append("static const BLORG_CONTRACT_LISTING BlorgContractListings[] =")
    out.append("{")
    out.extend(listings)
    out.append("};")
    out.append("")
    out.append("static const BLORG_CONTRACT_ENTRY BlorgContractEntries[] =")
    out.append("{")
    out.extend(entries)
    out.append("};")
    out.append("")
    return "\n".join(out)


