def render_rust(contract: dict, encoded: dict[str, bytes]) -> str:
    v = contract["version"]
    t = contract["transport"]
    routes = route_by_id(contract)
    out = [
        "// " + BANNER,
        "//",
        "// The server-rs <-> BlorgFS wire contract, for server-rs to `include!`.",
        "",
        "pub const VERSION_MAJOR: u32 = %d;" % v["major"],
        "pub const VERSION_MINOR: u32 = %d;" % v["minor"],
        "",
        "/// Query parameter carrying the request path.",
        "pub const QUERY_PATH: &str = %s;" % _rust_escape(t["query_path_key"]),
        "pub const MAX_BODY_BYTES: u64 = %d;" % t["max_body_bytes"],
        "pub const MAX_HEADER_BYTES: u64 = %d;" % t["max_header_bytes"],
        "",
        "pub mod route {",
    ]
    for route in contract["routes"]:
        out.append("    pub const %s: &str = %s;" % (route["id"], _rust_escape(route["path"])))
    out.append("}")
    out.append("")
    out.append("/// Success status per route, then the error statuses.")
    out.append("pub mod status {")
    for route in contract["routes"]:
        out.append("    pub const %s_OK: u16 = %d;" % (route["id"], route["success_status"]))
    for error in contract["error_statuses"]:
        out.append("    pub const %s: u16 = %d;" % (error["id"], error["status"]))
    out.append("}")
    out.append("")
    out.append("pub struct Behaviour {")
    out.append("    pub id: &'static str,")
    out.append("    pub title: &'static str,")
    out.append("    pub enforced: bool,")
    out.append("}")
    out.append("")
    out.append("pub const BEHAVIOURS: &[Behaviour] = &[")
    for b in contract["behaviours"]:
        out.append("    Behaviour { id: %s, title: %s, enforced: %s }," % (
            _rust_escape(b["id"]), _rust_escape(b["title"]), "true" if b["status"] == "enforced" else "false"))
    out.append("];")
    out.append("")
    out.append("pub struct Request {")
    out.append("    pub id: &'static str,")
    out.append("    pub route: &'static str,")
    out.append("    /// As the driver receives it from Windows.")
    out.append("    pub path: &'static str,")
    out.append("    /// Inclusive byte range.")
    out.append("    pub range: Option<(u64, u64)>,")
    out.append("    /// The exact bytes the driver sends.")
    out.append("    pub wire: &'static [u8],")
    out.append("}")
    out.append("")
    out.append("pub const REQUESTS: &[Request] = &[")
    for req in contract["requests"]:
        rng = "Some((%d, %d))" % tuple(req["range"]) if "range" in req else "None"
        out.append("    Request { id: %s, route: route::%s, path: %s, range: %s, wire: %s.as_bytes() }," % (
            _rust_escape(req["id"]), req["route"], _rust_escape(req["path"]), rng, _rust_escape(req["wire"])))
    out.append("];")
    out.append("")
    out.append("pub struct File {")
    out.append("    pub name: &'static str,")
    out.append("    pub size: u64,")
    out.append("    pub created: u64,")
    out.append("    pub modified: u64,")
    out.append("    pub accessed: u64,")
    out.append("}")
    out.append("")
    out.append("pub struct Subdirectory {")
    out.append("    pub name: &'static str,")
    out.append("    pub created: u64,")
    out.append("    pub modified: u64,")
    out.append("    pub accessed: u64,")
    out.append("}")
    out.append("")
    out.append("pub struct Listing {")
    out.append("    pub id: &'static str,")
    out.append("    /// Encoded by flatc, the reference encoder.")
    out.append("    pub bytes: &'static [u8],")
    out.append("    pub files: &'static [File],")
    out.append("    pub subdirectories: &'static [Subdirectory],")
    out.append("}")
    out.append("")
    out.append("pub struct Entry {")
    out.append("    pub id: &'static str,")
    out.append("    /// Encoded by flatc, the reference encoder.")
    out.append("    pub bytes: &'static [u8],")
    out.append("    pub size: u64,")
    out.append("    pub created: u64,")
    out.append("    pub modified: u64,")
    out.append("    pub accessed: u64,")
    out.append("    pub directory: bool,")
    out.append("}")
    out.append("")

    listings, entries = [], []
    for fixture in contract["fixtures"]:
        fid = fixture["id"]
        data = encoded[fid]
        bytes_literal = "&[\n%s\n    ]" % byte_rows(data, "        ")
        d = fixture["data"]
        if fixture["root_type"].endswith(".Directory"):
            files = "".join(
                "            File { name: %s, size: %d, created: %d, modified: %d, accessed: %d },\n" % (
                    _rust_escape(f["name"]), f["size"], f["created"], f["modified"], f["accessed"])
                for f in d["files"])
            subdirs = "".join(
                "            Subdirectory { name: %s, created: %d, modified: %d, accessed: %d },\n" % (
                    _rust_escape(s["name"]), s["created"], s["modified"], s["accessed"])
                for s in d["subdirectories"])
            listings.append(
                "    Listing {\n        id: %s,\n        bytes: %s,\n        files: &[\n%s        ],\n        subdirectories: &[\n%s        ],\n    }," % (
                    _rust_escape(fid), bytes_literal.replace("\n    ]", "\n        ]"), files, subdirs))
        else:
            entries.append(
                "    Entry {\n        id: %s,\n        bytes: %s,\n        size: %d,\n        created: %d,\n        modified: %d,\n        accessed: %d,\n        directory: %s,\n    }," % (
                    _rust_escape(fid), bytes_literal.replace("\n    ]", "\n        ]"), d["size"], d["created"], d["modified"], d["accessed"],
                    "true" if d["directory"] else "false"))

    out.append("pub const LISTINGS: &[Listing] = &[")
    out.extend(listings)
    out.append("];")
    out.append("")
    out.append("pub const ENTRIES: &[Entry] = &[")
    out.extend(entries)
    out.append("];")
    out.append("")
    return "\n".join(out)


