def validate(contract: dict) -> None:
    """Catch contract mistakes before they become generated code."""
    routes = route_by_id(contract)
    ids = [b["id"] for b in contract["behaviours"]]
    if len(ids) != len(set(ids)):
        sys.exit("duplicate behaviour id")
    for b in contract["behaviours"]:
        if b["status"] not in ("enforced", "gap"):
            sys.exit("%s: status must be enforced or gap" % b["id"])
    for req in contract["requests"]:
        route = routes[req["route"]]
        expected = encode_request(contract, route["path"], req["path"], req["host"], req.get("range"))
        if expected != req["wire"]:
            sys.exit("request %s: wire does not follow transport.path_encoding\n  want %r\n  have %r" % (
                req["id"], expected, req["wire"]))
    for fixture in contract["fixtures"]:
        if fixture["root_type"].endswith(".Directory"):
            names = [e["name"] for e in fixture["data"]["files"]] + [e["name"] for e in fixture["data"]["subdirectories"]]
            if len(names) != len(set(names)):
                sys.exit("fixture %s breaks B06: duplicate name" % fixture["id"])
            for group in ("files", "subdirectories"):
                group_names = [e["name"].encode("utf-8") for e in fixture["data"][group]]
                if group_names != sorted(group_names):
                    sys.exit("fixture %s breaks B06: %s not in byte-wise name order" % (fixture["id"], group))


SAFE = set(b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-._~")


def percent_encode(path: str) -> str:
    return "".join(chr(b) if b in SAFE else "%%%02X" % b for b in path.encode("utf-8"))


def encode_request(contract: dict, route_path: str, path: str, host: str, rng) -> str:
    key = contract["transport"]["query_path_key"]
    wire = "GET %s?%s=%s HTTP/1.1\r\nHost: %s\r\nConnection: keep-alive\r\n" % (route_path, key, percent_encode(path), host)
    if rng:
        wire += "Range: bytes=%d-%d\r\n" % (rng[0], rng[1])
    return wire + "\r\n"


def render_all(contract: dict, out_dir: Path) -> None:
    (out_dir / "fixtures").mkdir(parents=True, exist_ok=True)
    (out_dir / "generated").mkdir(parents=True, exist_ok=True)
    encoded = encode_fixtures(contract, out_dir)
    outputs = {
        "generated/blorg_contract.h": render_c_header(contract),
        "generated/blorg_contract_fixtures.h": render_c_fixtures(contract, encoded),
        "generated/blorg_contract.rs": render_rust(contract, encoded),
    }
    for rel, text in outputs.items():
        (out_dir / rel).write_bytes(text.encode("ascii"))


GENERATED = ["generated/blorg_contract.h", "generated/blorg_contract_fixtures.h", "generated/blorg_contract.rs"]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if committed outputs are stale")
    args = parser.parse_args()

    contract = load_contract()
    validate(contract)

    if not args.check:
        render_all(contract, ROOT)
        return 0

    with tempfile.TemporaryDirectory() as tmp:
        render_all(contract, Path(tmp))
        expected = GENERATED + ["fixtures/%s.bin" % f["id"] for f in contract["fixtures"]]
        stale = [rel for rel in expected
                 if not (ROOT / rel).exists() or (ROOT / rel).read_bytes() != (Path(tmp) / rel).read_bytes()]
    if stale:
        print("stale generated files (run python3 tools/generate.py and commit):", file=sys.stderr)
        for rel in stale:
            print("  " + rel, file=sys.stderr)
        return 1
    print("generated files are up to date with contract.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
