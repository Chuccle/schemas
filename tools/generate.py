#!/usr/bin/env python3
"""Generate every derived file in this repository from contract.json.

    python3 tools/generate.py           # rewrite fixtures/ and generated/
    python3 tools/generate.py --check   # fail if anything committed is stale

Outputs:
    fixtures/<ID>.bin                   FlatBuffer encoded by flatc (reference encoder)
    generated/blorg_contract.h          kernel-safe C macros (routes, statuses, version)
    generated/blorg_contract_fixtures.h C/C++ test fixtures (driver sandbox tests)
    generated/blorg_contract.rs         Rust constants and fixtures (server-rs)

flatc comes from $FLATC or PATH and must be the version in FLATC_VERSION below,
since that is the encoder server-rs builds with.

Standard library only, so it runs unchanged on the ubuntu and windows runners.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FLATC_VERSION = "25.12.19"
BANNER = "@generated by tools/generate.py from contract.json -- do not edit by hand."


def load_contract() -> dict:
    return json.loads((ROOT / "contract.json").read_text(encoding="utf-8"))


# ---------------------------------------------------------------------------
# fixtures/*.bin
# ---------------------------------------------------------------------------

def flatc_binary() -> str:
    flatc = os.environ.get("FLATC") or shutil.which("flatc")
    if not flatc:
        sys.exit("flatc not found: set FLATC or put flatc %s on PATH" % FLATC_VERSION)
    version = subprocess.run([flatc, "--version"], capture_output=True, text=True, check=True).stdout
    if FLATC_VERSION not in version:
        sys.exit("flatc %s required (server-rs pins it), found: %s" % (FLATC_VERSION, version.strip()))
    return flatc


def encode_fixtures(contract: dict, out_dir: Path) -> dict[str, bytes]:
    flatc = flatc_binary()
    schema = ROOT / contract["schema"]["file"]
    encoded = {}
    with tempfile.TemporaryDirectory() as tmp:
        for fixture in contract["fixtures"]:
            source = Path(tmp) / (fixture["id"] + ".json")
            source.write_text(json.dumps(fixture["data"]), encoding="utf-8")
            subprocess.run(
                [flatc, "--binary", "--root-type", fixture["root_type"], "-o", tmp, str(schema), str(source)],
                check=True,
            )
            encoded[fixture["id"]] = (Path(tmp) / (fixture["id"] + ".bin")).read_bytes()
    for fixture_id, data in encoded.items():
        (out_dir / "fixtures" / (fixture_id + ".bin")).write_bytes(data)
    return encoded


